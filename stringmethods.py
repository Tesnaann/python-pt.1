#lower
A="My name is Tesna"
print(A.lower()) 
#upper()
print(A.upper())
#capitialize-make first letter capital 
print(A.capitalize())
#swapcase-make capital into small and vice versa 
print(A.swapcase())
#partition
print(A.partition('is'))
#format
print(A.format)
b = 18
print("Hello, I am {} years old!".format(b))
#join
print(A.join("hello"))
#index-count index position
print(A.index('T'))
#strip,t removes all whitespace characters, 
print(A.strip())
#startswith-true or false
print(A.startswith("M"))
#endswith
print(A.endswith("c"))
#isalnum-contains alphabets/numbers
print(A.isalnum())